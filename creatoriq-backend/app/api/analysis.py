
"""AI-powered content analysis endpoint using local Ollama."""

import json

import httpx
from fastapi import APIRouter

from app.api.analysis_schemas import (
    ContentAnalysisRequest,
    ContentAnalysisResponse,
)

router = APIRouter(prefix="/analysis", tags=["Content Analysis"])

OLLAMA_URL = "http://localhost:11434/api/chat"
OLLAMA_MODEL = "qwen2.5:3b"


def estimate_production_minutes(content_format: str) -> int:
    """Return a rough initial production-time estimate."""
    estimates = {
        "Short video": 90,
        "Long video": 300,
        "Carousel": 60,
        "Image post": 30,
    }
    return estimates[content_format]


def suggest_structure(content_format: str) -> list[str]:
    """Suggest a simple structure based on the selected format."""
    structures = {
        "Short video": [
            "Hook: capture attention in the first 1–3 seconds",
            "Main value: explain one useful idea",
            "Payoff: show the result or key takeaway",
            "Call to action: invite a relevant response",
        ],
        "Long video": [
            "Opening hook and promise",
            "Introduction and context",
            "Main sections with examples",
            "Summary and call to action",
        ],
        "Carousel": [
            "Slide 1: clear, compelling headline",
            "Slides 2–5: one useful point per slide",
            "Final slide: summary and call to action",
        ],
        "Image post": [
            "Clear visual message",
            "Supporting caption",
            "Relevant call to action",
        ],
    }
    return structures[content_format]


def generate_ai_suggestions(
    idea: str,
    platform: str,
    content_format: str,
    audience: str,
) -> dict | None:
    """Ask the local Ollama model for content suggestions."""
    prompt = f"""
You are CreatorIQ, a practical social-media content strategist.

Create content suggestions for:
- Content idea: {idea}
- Platform: {platform}
- Format: {content_format}
- Target audience: {audience}

Return ONLY a valid JSON object with these two fields:
{{
  "hook_suggestion": "A compelling opening hook",
  "structure": [
    "Step 1",
    "Step 2",
    "Step 3",
    "Step 4"
  ]
}}

Requirements:
- Make the hook specific to the supplied idea and audience.
- Adapt the structure to the chosen platform and format.
- Avoid generic filler and unsupported factual claims.
- Return JSON only, without Markdown fences.
"""

    try:
        response = httpx.post(
            OLLAMA_URL,
            json={
                "model": OLLAMA_MODEL,
                "messages": [
                    {
                        "role": "system",
                        "content": (
                            "You generate useful social-media content plans. "
                            "Follow the requested JSON format exactly."
                        ),
                    },
                    {"role": "user", "content": prompt},
                ],
                "stream": False,
                "format": "json",
                "options": {"temperature": 0.7},
            },
            timeout=120.0,
        )
        response.raise_for_status()

        message = response.json()["message"]["content"]
        result = json.loads(message)

        hook = result.get("hook_suggestion")
        structure = result.get("structure")

        if (
            not isinstance(hook, str)
            or not hook.strip()
            or not isinstance(structure, list)
            or not structure
            or not all(isinstance(item, str) for item in structure)
        ):
            return None

        return {
            "hook_suggestion": hook.strip(),
            "structure": structure,
        }

    except (httpx.HTTPError, ValueError, KeyError, TypeError):
        return None


@router.post("", response_model=ContentAnalysisResponse)
def analyze_content(
    payload: ContentAnalysisRequest,
) -> ContentAnalysisResponse:
    """Generate AI suggestions, with a rule-based fallback."""
    idea = payload.idea.strip()
    audience = payload.target_audience.strip()

    ai_result = generate_ai_suggestions(
        idea=idea,
        platform=payload.platform,
        content_format=payload.content_format,
        audience=audience,
    )

    if ai_result:
        hook = ai_result["hook_suggestion"]
        structure = ai_result["structure"]
        analysis_type = "ollama_qwen2.5_3b"
        estimate_note = (
            "Hook and content plan generated by a local AI model. "
            "Production time is a rough rule-based estimate and may vary."
        )
    else:
        # Preserve a usable result if Ollama is unavailable.
        audience_lower = audience.lower()
        hook = (
            f"Here's one practical takeaway for {audience_lower}: {idea}"
        )
        structure = suggest_structure(payload.content_format)
        analysis_type = "rule_based_fallback"
        estimate_note = (
            "Local AI was unavailable, so a basic fallback was used. "
            "Production time is a rough estimate and varies with experience, "
            "complexity, revisions, and production setup."
        )

    return ContentAnalysisResponse(
        idea=idea,
        platform=payload.platform,
        content_format=payload.content_format,
        target_audience=audience,
        hook_suggestion=hook,
        structure=structure,
        estimated_production_minutes=estimate_production_minutes(
            payload.content_format
        ),
        estimate_note=estimate_note,
        analysis_type=analysis_type,
    )
